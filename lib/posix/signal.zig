const std = @import("std");

const cpuStateSize = switch (@import("builtin").cpu.arch) {
    .x86_64 => [20]u64,
    else => undefined,
};

const types = @import("types.zig");
const limits = @import("limits.zig");

const RTMIN = 32;

pub const Signal = enum(i32) {
    // Signal cannot be 0
    SIGABRT = 1,    // (A) Process abort signal
    SIGALRM = 2,    // (T) Alarm clock
    SIGBUS = 3,     // (A) Access to an undefined portion of a memory object
    SIGCHLD = 4,    // (I) Child process terminated, stopped, or continued
    SIGCONT = 5,    // (C) Continue executing, if stopped
    SIGFPE = 6,     // (A) Erroneous arithmetic operation
    SIGHUP = 7,     // (T) Hangup
    SIGILL = 8,     // (A) Illegal instruction
    SIGINT = 9,     // (T) Terminal interrupt signal
    SIGKILL = 10,   // (T) Kill (cannot be caught or ignored)
    SIGPIPE = 11,   // (T) Write on a pipe with no one to read it
    SIGQUIT = 12,   // (A) Terminal quit signal
    SIGSEGV = 13,   // (A) Invalid memory reference
    SIGSTOP = 14,   // (S) Stop executing (cannot be caught or ignored)
    SIGTERM = 15,   // (T) Termination signal
    SIGTSTP = 16,   // (S) Terminal stop signal
    SIGTTIN = 17,   // (S) Background process attempting read
    SIGTTOU = 18,   // (S) Background process attempting write
    SIGUSR1 = 19,   // (T) User-defined signal 1
    SIGUSR2 = 20,   // (T) User-defined signal 2
    SIGWINCH = 21,  // (I) Terminal window size changed
    SIGSYS = 22,    // (A) Bad system call
    SIGTRAP = 23,   // (A) Trace/breakpoint trap
    SIGURG = 24,    // (I) High bandwidth data is available at a socket
    SIGVTALRM = 25, // (T) Virtual timer expired
    SIGXCPU = 26,   // (A) CPU time limit exceeded
    SIGXFSZ = 27,   // (A) File size limit exceeded
    _,
};

pub const SIGRTMIN = 32;
pub const SIGRTMAX = SIGRTMIN + limits.RTSIG_MAX - 1;

pub const MINSIGSTKSZ = 0x800;
pub const SIGSTKSZ = 0x2000;

// Number of normal signals
pub const sigNumNormal = @intFromEnum(Signal.SIGXFSZ) + 1;

// Number of real-time signals
pub const sigNumRT = limits.RTSIG_MAX;

pub const SigHandler = enum(u64) {
    SIG_DFL = 0,
    SIG_IGN = 1,
    _,
};

pub const SIG_ERR : i32 = -1;

pub fn sigValid(sig : anytype) bool {
    return sig != 0
        and (sig <= @intFromEnum(Signal.SIGXFSZ) or sig >= SIGRTMIN)
        and sig <= SIGRTMAX;
}

pub fn sigIgnorable(sig : anytype) bool {
    const signal = @as(Signal, @enumFromInt(sig));
    return switch (signal) {
        .SIGKILL, .SIGSTOP => false,
        else => true,
    };
}

pub const SigAction = packed struct(i32) {
    SA_NOCLDSTOP : bool = false,   // Do not generate SIGCHLD when children stop or stopped children continue
    SA_ONSTACK : bool = false,     // Causes signal delivery to occur on an alternate stack
    SA_RESETHAND : bool = false,   // Causes signal dispositions to be set to SIG_DFL on entry to signal handlers
    SA_RESTART : bool = false,     // Causes certain functions to become restartable
    SA_SIGINFO : bool = false,     // Causes extra information to be passed to signal handlers at the time of receipt of a signal
    SA_NOCLDWAIT : bool = false,   // Causes implementations not to create zombie processes or status information on child termination
    SA_NODEFER : bool = false,     // Causes signal not to be automatically blocked on entry to signal handler
    __pad2 : u25 = undefined,
};

pub const SigStatus = packed struct(i32) {
    SS_ONSTACK : bool = false,  // Process is executing on an alternate signal stack
    SS_DISABLE : bool = false,  // Alternate signal stack is disabled
    __pad1 : u30 = undefined,
};

pub const SigCode = enum(i32) {
    // Other
    SI_USER,            // Signal sent by kill()
    SI_QUEUE,           // Signal sent by sigqueue()
    SI_TIMER,           // Signal generated by expiration of a timer set by timer_settime()
    SI_ASYNCIO,         // Signal generated by completion of an asynchronous I/O request
    SI_MESGQ,           // Signal generated by arrival of a message on an empty message queue
    // SIGILL codes
    ILL_ILLOPC,         // Illegal opcode
    ILL_ILLOPN,         // Illegal operand
    ILL_ILLADR,         // Illegal addressing mode
    ILL_ILLTRP,         // Illegal trap
    ILL_PRVOPC,         // Privileged opcode
    ILL_PRVREG,         // Privileged register
    ILL_COPROC,         // Coprocessor error
    ILL_BADSTK,         // Internal stack error
    // SIGFPE codes
    FPE_INTDIV,         // Integer divide by zero
    FPE_INTOVF,         // Integer overflow
    FPE_FLTDIV,         // Floating-point divide by zero
    FPE_FLTOVF,         // Floating-point overflow
    FPE_FLTUND,         // Floating-point underflow
    FPE_FLTRES,         // Floating-point inexact result
    FPE_FLTINV,         // Invalid floating-point operation
    FPE_FLTSUB,         // Subscript out of range
    // SIGSEGV codes
    SEGV_MAPERR,        // Address not mapped to object
    SEGV_ACCERR,        // Invalid permissions for mapped object
    // SIGBUD codes
    BUS_ADRALN,         // Invalid address alignment
    BUS_ADRERR,         // Nonexistent physical address
    BUS_OBJERR,         // Object-specific hardware error
    // SIGTRAP codes
    TRAP_BRKPT,         // Process breakpoint
    TRAP_TRACE,         // Process trace trap
    // SIGCHLD codes
    CLD_EXITED,         // Child has exited
    CLD_KILLED,         // Child has terminated abnormally with no additional actions
    CLD_DUMPED,         // Child has terminated abnormally and additional actions may have been taken
    CLD_TRAPPED,        // Traced child has trapped
    CLD_STOPPED,        // Child has stopped
    CLD_CONTINUED,      // Stopped child has continued
    _,
};

pub const SigSet = enum(i32) {
    SIG_BLOCK = 0,
    SIG_SETMASK = 1,
    SIG_UNBLOCK = 2,
    _,
};

pub const sigval = extern union {
    sival_int : i32,
    sival_ptr : *anyopaque,
};

pub const siginfo_t = extern struct {
    si_signo : Signal,         // Signal number
    si_code : SigCode = @enumFromInt(0),          // Signal code
    si_errno : i32 = 0,         // If non-zero, an errno value associated with this signal, as described in <errnoh>
    si_pid : types.pid_t = 0,   // Sending process ID
    si_uid : types.uid_t = 0,   // Real user ID of sending process
    si_addr : *allowzero anyopaque = @ptrFromInt(0),   // Address that caused fault
    si_status : i32 = 0,        // Exit value or signal
    si_value : sigval = .{.sival_int = 0},      // Signal value
};

pub const stack_t = extern struct {
    ss_sp : *anyopaque,     // Stack base or pointer.
    ss_size : usize,        // Stack size.
    ss_flags : SigStatus,   // Flags.
};

pub const sigset_t = u64;

pub const sigaction = extern struct {
    sa_handler : SigHandler,    // Pointer to a signal-catching function or SIG_IGN or SIG_DFL or sa_sigaction
    sa_mask : sigset_t,     // Set of signals to be blocked during execution of the signal handling function
    sa_flags : SigAction,   // Special flags
};

pub const sigevent = extern struct {
    sigev_notify : i32,                         // Notification type.
    sigev_signo : i32,                          // Signal number.
    sigev_value : sigval,                       // Signal value.
    sigev_notify_function : u64,                // Notification function
    sigev_notify_attributes : u8 = undefined,   // Notification attributes
};

pub const ucontext_t = extern struct {
    uc_link : ?*ucontext_t,  // Pointer to the context that is resumed
    uc_sigmask : sigset_t,  // The set of signals that are blocked when this context is active
    uc_stack : stack_t,     // The stack used by this context.
    uc_mcontext : cpuStateSize,  // A machine-specific representation of the saved context.
};